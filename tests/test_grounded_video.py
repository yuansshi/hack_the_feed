def test_poll_download_is_unreviewed_and_never_a_new_generation(job):
    path, _, _ = job
    video.write_json(path / 'state.json', {'status': 'queued', 'request_id': 'request-123'})
    requests = []
    media = b'simulated generated bytes' * 100

    def transport(request):
        requests.append(request)
        assert request.method == 'GET'
        if request.url.host == 'console.gmicloud.ai':
            return httpx.Response(200, json={'status': 'success', 'outcome': {'video_url': 'https://storage.googleapis.com/pilot.mp4'}})
        assert 'authorization' not in request.headers
        return httpx.Response(200, content=media)

    with httpx.Client(transport=httpx.MockTransport(transport)) as client:
        state = video.poll(path, 'project-test-placeholder', client)
        assert state['status'] == 'generated_unreviewed'
        assert state['sha256'] == video.digest(media)
        assert video.poll(path, 'project-test-placeholder', client) == state
    assert len(requests) == 2
    assert not (path.parent.parent / 'generated_videos.json').exists()


def test_missing_project_credential_does_not_read_personal_environment(monkeypatch):
    monkeypatch.delenv('HOMI_GMI_API_KEY', raising=False)
    original_get = video.os.environ.get

    def project_only(name, default=None):
        assert name == 'HOMI_GMI_API_KEY'
        return original_get(name, default)

    monkeypatch.setattr(video.os.environ, 'get', project_only)
    with pytest.raises(ValueError, match='Configure the project'):
        video.credential()
